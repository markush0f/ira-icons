import { readFile, readdir, writeFile } from 'node:fs/promises';
import { interfaceIcons } from './interface.ts';
import { fileIcons } from './files.ts';
import { digitalIcons } from './digital.ts';
import { weatherIcons } from './weather.ts';
import { travelIcons } from './travel.ts';
import { mediaIcons } from './media.ts';
import { commerceIcons } from './commerce.ts';
import { scienceIcons } from './science.ts';
import { natureIcons } from './nature.ts';
import { homeFoodIcons } from './home-food.ts';
import { svg } from './geometry.ts';
import { designRevealFor } from './design-reveal.ts';
import { renderStrokeReveal } from './stroke-reveal.ts';
import { arrowRevealFor, renderArrowReveal } from './arrow-reveal.ts';
import tablerRows from './folio/tabler.json' with { type: 'json' };
import { placeIcons } from './atlas/places.ts';
import { panelIcons } from './atlas/panels.ts';
import { tabletopIcons } from './atlas/tabletop.ts';
import { folioIcons } from './folio/families.ts';

const folioPaths = new Map((tablerRows as [string, string, string[]][]).map(([,name,paths]) => [name,paths]));
const collection = [folioIcons, placeIcons, panelIcons, tabletopIcons, interfaceIcons, fileIcons, digitalIcons, weatherIcons, travelIcons, mediaIcons, commerceIcons, scienceIcons, natureIcons, homeFoodIcons].flat();
const root = new URL('../../', import.meta.url);
const check = process.argv.includes('--check');
// Preserve the historical marker so migration does not rewrite original assets.
const marker = '<!-- Generated by scripts/icon-expansion/generate.mjs -->';
const header = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2" viewBox="0 0 24 24">';
const wrap = (parts: string[], notice?: string, generatedMarker = marker) => [header, `    ${generatedMarker}`, ...(notice ? [`    <!-- ${notice} -->`] : []), ...parts.map((part) => part.replace(/^/gm, '    ')), '</svg>', ''].join('\n');
const files = new Map<string, string>();
const names = new Set<string>();
const outlines = new Set<string>();

for (const icon of collection) {
  const { name, outline, detail, minimal } = icon;
  if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name) || names.has(name)) {
    throw new Error(`Invalid icon definition: ${name}`);
  }
  names.add(name);
  const original = [svg(outline), ...(detail ? [svg(detail)] : [])];
  const geometry = original.join('');
  if (outlines.has(geometry)) throw new Error(`Duplicate original geometry for ${name}`);
  if (geometry === svg(minimal)) throw new Error(`Missing minimalist geometry for ${name}`);
  outlines.add(geometry);
  files.set(`${name}.svg`, wrap(original, icon.notice));
  files.set(`${name}-minimalist.svg`, wrap([svg(minimal)], icon.notice));
  const arrow = arrowRevealFor(name, folioPaths.get(name));
  const sequence = arrow ? renderArrowReveal(name, arrow) : designRevealFor(name, geometry)
    ?? renderStrokeReveal(name, geometry);
  files.set(`${name}-animated.svg`, wrap(sequence, icon.notice));
}

// The global tracing rule also adopts every legacy animated variant. Only the
// animated file is regenerated; original root attributes and license notices stay.
const adopted = new Set<string>();
for (const filename of await readdir(new URL('icons/', root))) {
  if (!filename.endsWith('.svg') || /-(animated|minimalist)\.svg$/.test(filename)) continue;
  const name = filename.slice(0, -4);
  if (names.has(name)) continue;
  const original = await readFile(new URL(`icons/${filename}`, root), 'utf8');
  const opening = original.match(/^<svg[^>]*>/)?.[0];
  if (!opening) throw Error(`Missing SVG root: ${name}`);
  const body = original.replace(/^<svg[^>]*>\s*|\s*<\/svg>\s*$/g, '');
  const arrow = arrowRevealFor(name);
  const design = arrow ? undefined : designRevealFor(name, body);
  const parts = arrow ? renderArrowReveal(name, arrow) : design ?? renderStrokeReveal(name, body);
  const source = arrow ? 'arrow-reveal' : design ? 'design-reveal' : 'stroke-reveal';
  const contents = wrap(parts, undefined, `<!-- Generated by scripts/icon-expansion/${source}.ts -->`).replace(header, opening);
  files.set(`${name}-animated.svg`, contents);
  adopted.add(`${name}-animated.svg`);
}

const changed: [URL, string][] = [];
const existing = await readdir(new URL('icons/', root));
for (const [filename, contents] of files) {
  const url = new URL(`icons/${filename}`, root);
  const previous = await readFile(url, 'utf8').catch((error) => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (previous?.replaceAll('\r\n', '\n') === contents.replaceAll('\r\n', '\n')) continue;
  if (previous !== null && !previous.includes(marker) && !adopted.has(filename)) throw new Error(`Refusing to overwrite ${filename}`);
  if (check) throw new Error(`Missing or out-of-date SVG: ${filename}`);
  changed.push([url, contents]);
}
// Bound simultaneous handles even on a clean checkout generating thousands of files.
for (let i = 0; i < changed.length; i += 32) {
  await Promise.all(changed.slice(i, i+32).map(([url, text]) => writeFile(url, text)));
}

const all = [...new Set([...existing, ...files.keys()])]
  .filter((filename) => filename.endsWith('.svg') && !/-(animated|minimalist)\.svg$/.test(filename))
  .map((filename) => filename.slice(0, -4)).sort();
const rows = [];
for (let index = 0; index < all.length; index += 8) rows.push(`      ${all.slice(index, index + 8).map(name => JSON.stringify(name)).join(', ')}`);
const replacements: [string, RegExp, string][] = [
  ['index.html', /    const icons = \[[\s\S]*?\];/, `    const icons = [\n${rows.join(',\n')}\n    ];`],
  ['README.md', /A collection of \d+ icons in three styles/, `A collection of ${all.length} icons in three styles`],
];
for (const [filename, pattern, replacement] of replacements) {
  const url = new URL(filename, root);
  const content = await readFile(url, 'utf8');
  if (!pattern.test(content)) throw new Error(`Could not find catalog metadata in ${filename}`);
  const next = content.replace(pattern, replacement);
  if (next === content) continue;
  if (check) throw new Error(`Out-of-date catalog metadata in ${filename}`);
  await writeFile(url, next);
}
console.log(`${collection.length} generated families (${files.size} SVGs); ${all.length} families in the catalog.`);
