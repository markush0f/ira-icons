function animated({ name, outline, detail, motion }: import('./geometry.ts').IconDefinition) {
  const [seconds, frames, timing = 'ease-in-out'] = motions[motion];
  const keyframes = `ira-exp-${motion}`;
  const selector = `[data-ira-motion="${name}"]`;
  const layer = svg(detail || outline);
  const phase = [...name].reduce((sum, char) => sum + char.charCodeAt(0), 0) % 11 / 10;
  const fixedOrigin = ({ safe: '14px 12px', stopwatch: '12px 13px', gauge: '12px 16px' } as Record<string, string>)[name];
  const boxOrigin = fixedOrigin || ['spin', 'tick', 'bars'].includes(motion)
    ? `transform-origin: ${fixedOrigin || '12px 12px'}; `
    : 'transform-box: fill-box; transform-origin: center; ';
  const rule = motion === 'trace'
    ? `            ${selector} path { stroke-dasharray: 1 2; animation: ${keyframes} ${seconds}s ${timing} -${phase}s infinite; }`
    : motion === 'signal'
      ? `            ${selector} > * { animation: ${keyframes} ${seconds}s ${timing} infinite; }\n            ${selector} > :nth-child(2) { animation-delay: -2s; }\n            ${selector} > :nth-child(3) { animation-delay: -1s; }`
      : `            ${selector} { ${boxOrigin}animation: ${keyframes} ${seconds}s ${timing} -${phase}s infinite; }`;
  const drawing = motion === 'trace' ? layer.replaceAll('<path ', '<path pathLength="1" ') : layer;
  return [
    '<style>',
    '    @media (prefers-reduced-motion: no-preference) {',
    `        @keyframes ${keyframes} { ${frames} }`,
    rule.trimStart().split('\n').map((line) => line.trimStart()).map((line) => `        ${line}`).join('\n'),
    '    }',
    '</style>',
    ...(detail ? [svg(outline)] : []),
    `<g data-ira-motion="${name}">${drawing}</g>`,
  ];
}

const wrap = (parts: string[], notice?: string, generatedMarker = marker) => [header, `    ${generatedMarker}`, ...(notice ? [`    <!-- ${notice} -->`] : []), ...parts.map((part) => part.replace(/^/gm, '    ')), '</svg>', ''].join('\n');
const files = new Map();
const names = new Set();
const outlines = new Set();
for (const icon of collection) {
  const { name, outline, detail, minimal, motion } = icon;
  if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name) || names.has(name) || !motions[motion]) {
    throw new Error(`Invalid icon definition: ${name}`);
  }
  names.add(name);
  const original = [svg(outline), ...(detail ? [svg(detail)] : [])];
  const geometry = original.join('');
  if (outlines.has(geometry)) throw new Error(`Duplicate original geometry for ${name}`);
  if (geometry === svg(minimal)) throw new Error(`Missing minimalist geometry for ${name}`);
  outlines.add(geometry);
  files.set(`${name}.svg`, wrap(original, icon.notice));
  files.set(`${name}-minimalist.svg`, wrap([svg(minimal)], icon.notice));
  const reveal = arrowRevealFor(name, folioPaths.get(name));
  const sequence = reveal ? renderArrowReveal(name, reveal) : designRevealFor(name, geometry)
    ?? (icon.sequence ? renderPlan(name, icon.sequence) : animated(icon));
  files.set(`${name}-animated.svg`, wrap(sequence, icon.notice));
}

// Only these explicitly adopted legacy animated variants are now generated.
const revealMarker = '<!-- Generated by scripts/icon-expansion/arrow-reveal.ts -->';
const manualDesignReveals = ['activity', 'chart-bar', 'chart-line', 'grid', 'table'];
const adopted = new Set([...manualArrowReveals, ...manualDesignReveals].map(name => `${name}-animated.svg`));
for (const name of manualArrowReveals) {
  if (names.has(name)) throw Error(`Duplicate arrow reveal: ${name}`);
  files.set(`${name}-animated.svg`, wrap(renderArrowReveal(name, arrowRevealFor(name)!), undefined, revealMarker));
}

for (const name of manualDesignReveals) {
  if (names.has(name)) throw Error(`Duplicate design reveal: ${name}`);
  const original = await readFile(new URL(`icons/${name}.svg`, root), 'utf8');
  const body = original.replace(/^<svg[^>]*>\s*|\s*<\/svg>\s*$/g, '');
  const reveal = designRevealFor(name, body);
  if (!reveal) throw Error(`Missing design reveal: ${name}`);
  files.set(`${name}-animated.svg`, wrap(reveal, undefined, '<!-- Generated by scripts/icon-expansion/design-reveal.ts -->'));
}

const changed: [URL, string][] = [];
const existing = await readdir(new URL('icons/', root));
for (const [filename, contents] of files) {
  const url = new URL(`icons/${filename}`, root);
  const previous = await readFile(url, 'utf8').catch((error) => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (previous?.replaceAll('\r\n', '\n') === contents.replaceAll('\r\n', '\n')) continue;
  if (previous !== null && !previous.includes(marker) && !adopted.has(filename)) throw new Error(`Refusing to overwrite ${filename}`);
  if (check) throw new Error(`Missing or out-of-date SVG: ${filename}`);
  changed.push([url, contents]);
}
// Bound simultaneous handles even on a clean checkout generating thousands of files.
for (let i = 0; i < changed.length; i += 32) {
  await Promise.all(changed.slice(i, i+32).map(([url, text]) => writeFile(url, text)));
}

const all = [...new Set([...existing, ...files.keys()])]
  .filter((filename) => filename.endsWith('.svg') && !/-(animated|minimalist)\.svg$/.test(filename))
  .map((filename) => filename.slice(0, -4)).sort();
const rows = [];
for (let index = 0; index < all.length; index += 8) rows.push(`      ${all.slice(index, index + 8).map(name => JSON.stringify(name)).join(', ')}`);
const replacements: [string, RegExp, string][] = [
  ['index.html', /    const icons = \[[\s\S]*?\];/, `    const icons = [\n${rows.join(',\n')}\n    ];`],
  ['README.md', /A collection of \d+ icons in three styles/, `A collection of ${all.length} icons in three styles`],
];
for (const [filename, pattern, replacement] of replacements) {
  const url = new URL(filename, root);
  const content = await readFile(url, 'utf8');
  if (!pattern.test(content)) throw new Error(`Could not find catalog metadata in ${filename}`);
  const next = content.replace(pattern, replacement);
  if (next === content) continue;
  if (check) throw new Error(`Out-of-date catalog metadata in ${filename}`);
  await writeFile(url, next);
}
console.log(`${collection.length} generated families (${files.size} SVGs); ${all.length} families in the catalog.`);
