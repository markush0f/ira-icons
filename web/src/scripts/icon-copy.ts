export type CodeFormat = 'React' | 'Next.js' | 'Astro' | 'Vue' | 'Svelte' | 'SVG';

const escapeText = (value: string) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;');
const escapeAttribute = (value: string) => escapeText(value).replaceAll('"', '&quot;');

function serializeSvgElement(element: Element, depth: number): string {
  const indent = '  '.repeat(depth);
  const tag = element.localName;
  const attrs = Array.from(element.attributes, ({ name, value }) => ` ${name}="${escapeAttribute(value)}"`).join('');
  const children = Array.from(element.children);
  const text = element.textContent?.trim() ?? '';
  if (children.length) {
    return `${indent}<${tag}${attrs}>\n${children.map(child => serializeSvgElement(child, depth + 1)).join('\n')}\n${indent}</${tag}>`;
  }
  return text ? `${indent}<${tag}${attrs}>${escapeText(text)}</${tag}>` : `${indent}<${tag}${attrs} />`;
}

function literalSvg(preview: SVGSVGElement, color: string | null) {
  const attrs = new Map(Array.from(preview.attributes, ({ name, value }) => [name, value]));
  attrs.set('xmlns', 'http://www.w3.org/2000/svg');
  attrs.set('width', '24');
  attrs.set('height', '24');
  attrs.delete('color');
  attrs.delete('aria-hidden');
  if (color) attrs.set('stroke', color);
  const root = Array.from(attrs, ([name, value]) => `  ${name}="${escapeAttribute(value)}"`).join('\n');
  const children = Array.from(preview.children, child => serializeSvgElement(child, 1)).join('\n');
  return `<svg\n${root}\n>\n${children}\n</svg>\n`;
}

export function formatIcon(preview: SVGSVGElement, name: string, format: CodeFormat, speed = 1) {
  const color = preview.getAttribute('color');
  if (format === 'SVG') return literalSvg(preview, color);

  // Match the PascalCase exports generated by scripts/npm-package/build.ts.
  const component = name.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('');
  const colorProp = color && color !== 'currentColor' ? ` color="${escapeAttribute(color)}"` : '';
  const speedProp = name.endsWith('-animated') && speed !== 1
    ? (format === 'Vue' ? ` :speed="${speed}"` : ` speed={${speed}}`) : '';
  const usage = `<${component} ${format === 'Vue' ? ':size="24"' : 'size={24}'}${colorProp}${speedProp} />`;
  const reactImport = `import { ${component} } from '@ira-icons/iraicons/react';`;

  switch (format) {
    case 'React':
    case 'Next.js':
      return `${reactImport}\n\n${usage}\n`;
    case 'Astro':
      return `---\nimport ${component} from '@ira-icons/iraicons/astro/${name}';\n---\n\n${usage}\n`;
    case 'Vue':
      return `<script setup>\nimport { ${component} } from '@ira-icons/iraicons/vue';\n</script>\n\n<template>\n  ${usage}\n</template>\n`;
    case 'Svelte':
      return `<script>\n  import { ${component} } from '@ira-icons/iraicons/svelte';\n</script>\n\n${usage}\n`;
  }
}
